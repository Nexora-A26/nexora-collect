  if not found then raise exception 'العميل غير موجود.'; end if;
  return v_row;
end;
$$;

create or replace function public.remove_representative(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_count bigint;
begin
  if not public.has_permission('representatives','delete') then raise exception 'ليس لديك صلاحية حذف المندوب.'; end if;
  if not public.can_access_representative(p_id) then raise exception 'ليس لديك صلاحية الوصول إلى هذا المندوب.'; end if;
  if not exists(select 1 from public.representatives where id=p_id) then raise exception 'المندوب غير موجود.'; end if;
  select (select count(*) from public.receivables where representative_id=p_id) +
         (select count(*) from public.collections where representative_id=p_id) +
         (select count(*) from public.settlements where representative_id=p_id) into v_count;
  if v_count>0 then
    update public.representatives set status='inactive',updated_at=now() where id=p_id;
    return jsonb_build_object('deactivated',true);
  end if;
  update public.customers set representative_id=null,updated_at=now() where representative_id=p_id;
  delete from public.representatives where id=p_id;
  return jsonb_build_object('deactivated',false);
end;
$$;

create or replace function public.remove_customer(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count bigint;
  v_rep bigint;
begin
  if not public.has_permission('customers','delete') then raise exception 'ليس لديك صلاحية حذف العميل.'; end if;
  select representative_id into v_rep from public.customers where id=p_id;
  if not found then raise exception 'العميل غير موجود.'; end if;
  if not public.can_access_representative(v_rep) then raise exception 'ليس لديك صلاحية الوصول إلى هذا العميل.'; end if;
  select (select count(*) from public.receivables where customer_id=p_id) +
         (select count(*) from public.collections where customer_id=p_id) into v_count;
  if v_count>0 then
    update public.customers set status='inactive',updated_at=now() where id=p_id;
    return jsonb_build_object('deactivated',true);
  end if;
  delete from public.customers where id=p_id;
  return jsonb_build_object('deactivated',false);
end;
$$;

create or replace function public.remove_receivable(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count bigint;
  v_rep bigint;
begin
  if not public.has_permission('receivables','delete') then raise exception 'ليس لديك صلاحية حذف المبلغ المستحق.'; end if;
  select representative_id into v_rep from public.receivables where id=p_id;
  if not found then raise exception 'المبلغ المستحق غير موجود.'; end if;
  if not public.can_access_representative(v_rep) then raise exception 'ليس لديك صلاحية الوصول إلى هذا المبلغ.'; end if;
  select count(*) into v_count from public.collections where receivable_id=p_id;
  if v_count>0 then
    update public.receivables set status='cancelled',updated_at=now() where id=p_id;
    return jsonb_build_object('cancelled',true);
  end if;
  delete from public.receivables where id=p_id;
  return jsonb_build_object('cancelled',false);
end;
$$;

create or replace function public.dashboard_data()
returns jsonb
language sql
security definer
set search_path = ''
as $$
select case when public.has_permission('dashboard','view') then jsonb_build_object(
  'totals', jsonb_build_object(
    'representatives',(select count(*) from public.representatives r where r.status='active' and public.can_access_representative(r.id)),
    'customers',(select count(*) from public.customers c where c.status='active' and public.can_access_representative(c.representative_id)),
    'receivables',(select coalesce(sum(rv.original_amount),0) from public.receivables rv where rv.status<>'cancelled' and public.can_access_representative(rv.representative_id)),
    'collected',(select coalesce(sum(cl.amount),0) from public.collections cl where cl.status='active' and public.can_access_representative(cl.representative_id)),
    'remaining',(select coalesce(sum(rv.remaining_amount),0) from public.receivables rv where rv.status<>'cancelled' and public.can_access_representative(rv.representative_id)),
    'commissions',(select coalesce(sum(cl.commission_amount),0) from public.collections cl where cl.status='active' and public.can_access_representative(cl.representative_id)),
    'net',(select coalesce(sum(cl.net_amount),0) from public.collections cl where cl.status='active' and public.can_access_representative(cl.representative_id)),
    'today',(select coalesce(sum(cl.amount),0) from public.collections cl where cl.status='active' and cl.collection_date=current_date and public.can_access_representative(cl.representative_id)),
    'month',(select coalesce(sum(cl.amount),0) from public.collections cl where cl.status='active' and date_trunc('month',cl.collection_date)=date_trunc('month',current_date) and public.can_access_representative(cl.representative_id))
  ),
  'recent',coalesce((select jsonb_agg(x order by x.collection_date desc,x.id desc) from (
    select cl.id,cl.receipt_number,cl.amount,cl.commission_amount,cl.net_amount,cl.collection_date,cl.payment_method,cu.name customer_name,r.name representative_name
    from public.collections cl
    join public.customers cu on cu.id=cl.customer_id
    left join public.representatives r on r.id=cl.representative_id
    where cl.status='active' and public.can_access_representative(cl.representative_id)
    order by cl.collection_date desc,cl.id desc limit 10
  ) x),'[]'::jsonb),
  'trend',coalesce((select jsonb_agg(x order by x.date) from (
    select cl.collection_date date,sum(cl.amount) amount
    from public.collections cl
    where cl.status='active' and cl.collection_date>=current_date-29 and public.can_access_representative(cl.representative_id)
    group by cl.collection_date
  ) x),'[]'::jsonb),
  'topReps',coalesce((select jsonb_agg(x order by x.amount desc) from (
    select r.name,coalesce(sum(c.amount),0) amount
    from public.representatives r
    left join public.collections c on c.representative_id=r.id and c.status='active'
    where public.can_access_representative(r.id)
    group by r.id,r.name order by amount desc limit 5
  ) x),'[]'::jsonb),
  'topDebtors',coalesce((select jsonb_agg(x order by x.remaining desc) from (
    select c.name,coalesce(sum(rv.remaining_amount),0) remaining
    from public.customers c
    left join public.receivables rv on rv.customer_id=c.id and rv.status<>'cancelled'
    where public.can_access_representative(c.representative_id)
    group by c.id,c.name having coalesce(sum(rv.remaining_amount),0)>0
    order by remaining desc limit 5
  ) x),'[]'::jsonb)
) else null end
$$;

