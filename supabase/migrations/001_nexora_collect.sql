create or replace function public.assign_codes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_prefix text;
begin
  if tg_table_name = 'representatives' and coalesce(new.code,'') = '' then
    new.code := 'REP-' || lpad(nextval('public.representative_code_seq')::text, 6, '0');
  elsif tg_table_name = 'customers' and coalesce(new.code,'') = '' then
    new.code := 'CUS-' || lpad(nextval('public.customer_code_seq')::text, 6, '0');
  elsif tg_table_name = 'receivables' and coalesce(new.number,'') = '' then
    new.number := 'INV-' || lpad(nextval('public.receivable_number_seq')::text, 7, '0');
  elsif tg_table_name = 'collections' and coalesce(new.receipt_number,'') = '' then
    select receipt_prefix into v_prefix from public.settings where id = 1;
    new.receipt_number := coalesce(nullif(v_prefix,''),'REC') || '-' || lpad(nextval('public.collection_receipt_seq')::text, 7, '0');
  elsif tg_table_name = 'settlements' and coalesce(new.number,'') = '' then
    select settlement_prefix into v_prefix from public.settings where id = 1;
    new.number := coalesce(nullif(v_prefix,''),'SET') || '-' || lpad(nextval('public.settlement_number_seq')::text, 7, '0');
  end if;
  return new;
end;
$$;

create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_profile public.profiles;
  v_action text;
  v_old jsonb;
  v_new jsonb;
  v_id text;
begin
  select * into v_profile from public.profiles p where p.auth_user_id = auth.uid() limit 1;
  v_action := lower(tg_op);
  if tg_op = 'INSERT' then
    v_new := to_jsonb(new); v_id := new.id::text;
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old); v_new := to_jsonb(new); v_id := new.id::text;
  else
    v_old := to_jsonb(old); v_id := old.id::text;
  end if;
  insert into public.audit_logs(user_id,username,action,entity_type,entity_id,old_values,new_values)
  values(v_profile.id,coalesce(v_profile.username::text,'system'),v_action,tg_argv[0],v_id,v_old,v_new);
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

create or replace function public.refresh_receivable(p_receivable_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_original numeric;
  v_cancelled boolean;
  v_due date;
  v_paid numeric;
  v_remaining numeric;
  v_status text;
begin
  select original_amount, status = 'cancelled', due_date
    into v_original, v_cancelled, v_due
  from public.receivables where id = p_receivable_id;
  if not found then return; end if;
  select coalesce(sum(amount),0) into v_paid
  from public.collections where receivable_id = p_receivable_id and status = 'active';
  v_remaining := greatest(0, v_original - v_paid);
  if v_cancelled then v_status := 'cancelled';
  elsif v_remaining <= 0 then v_status := 'paid';
  elsif v_paid > 0 then v_status := 'partial';
  elsif v_due is not null and v_due < current_date then v_status := 'overdue';
  else v_status := 'unpaid'; end if;
  update public.receivables
     set paid_amount = v_paid, remaining_amount = v_remaining, status = v_status, updated_at = now()
   where id = p_receivable_id;
end;
$$;

create or replace function public.collections_refresh_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op in ('UPDATE','DELETE') then perform public.refresh_receivable(old.receivable_id); end if;
  if tg_op in ('INSERT','UPDATE') then perform public.refresh_receivable(new.receivable_id); end if;
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

create or replace function public.refresh_overdue_receivables()
returns void
language sql
security definer
set search_path = ''
as $$
  update public.receivables
     set status = case
       when remaining_amount <= 0 then 'paid'
       when paid_amount > 0 then 'partial'
       when due_date is not null and due_date < current_date then 'overdue'
       else 'unpaid'
     end,
     updated_at = now()
   where status <> 'cancelled'
$$;

create or replace function public.create_collection(p_values jsonb)
returns public.collections
language plpgsql
security invoker
as $$
declare
  v_rec public.receivables;
  v_existing public.collections;
  v_amount numeric;
  v_pct numeric;
  v_commission numeric;
  v_row public.collections;
begin
  if p_values ? 'operation_token' and nullif(p_values->>'operation_token','') is not null then
    select * into v_existing from public.collections where operation_token = (p_values->>'operation_token')::uuid;
    if found then return v_existing; end if;
  end if;
  select * into v_rec from public.receivables where id = (p_values->>'receivable_id')::bigint for update;
  if not found or v_rec.status = 'cancelled' then raise exception 'المبلغ المستحق غير موجود أو ملغى.'; end if;
  v_amount := (p_values->>'amount')::numeric;
  if v_amount <= 0 then raise exception 'المبلغ المقبوض يجب أن يكون أكبر من صفر.'; end if;
  if v_amount > v_rec.remaining_amount then raise exception 'المبلغ المقبوض أكبر من المبلغ المتبقي.'; end if;
  v_pct := coalesce(nullif(p_values->>'commission_percentage','')::numeric, v_rec.commission_percentage);
  if v_pct < 0 or v_pct > 100 then raise exception 'نسبة العمولة يجب أن تكون بين 0 و100.'; end if;
  v_commission := round(v_amount * v_pct / 100, 4);
  insert into public.collections(operation_token,receipt_number,customer_id,receivable_id,representative_id,amount,commission_percentage,commission_amount,net_amount,collection_date,payment_method,notes,status,created_by)
  values(
    nullif(p_values->>'operation_token','')::uuid,
    coalesce(p_values->>'receipt_number',''),
    v_rec.customer_id,
    v_rec.id,
    v_rec.representative_id,
    v_amount,
    v_pct,
    v_commission,
    v_amount - v_commission,
    coalesce(nullif(p_values->>'collection_date','')::date,current_date),
    coalesce(nullif(p_values->>'payment_method',''),'cash'),
    coalesce(p_values->>'notes',''),
    'active',
    public.current_profile_id()
  ) returning * into v_row;
  return v_row;
end;
$$;

create or replace function public.update_collection(p_id bigint, p_values jsonb)
returns public.collections
language plpgsql
security invoker
as $$
declare
  v_old public.collections;
  v_rec public.receivables;
  v_amount numeric;
  v_pct numeric;
  v_commission numeric;
  v_available numeric;
  v_row public.collections;
begin
  select * into v_old from public.collections where id = p_id for update;
  if not found then raise exception 'عملية القبض غير موجودة.'; end if;
  if v_old.status = 'cancelled' then raise exception 'لا يمكن تعديل عملية ملغاة.'; end if;
  select * into v_rec from public.receivables where id = coalesce(nullif(p_values->>'receivable_id','')::bigint,v_old.receivable_id) for update;
  if not found or v_rec.status = 'cancelled' then raise exception 'المبلغ المستحق غير موجود أو ملغى.'; end if;
  v_amount := coalesce(nullif(p_values->>'amount','')::numeric,v_old.amount);
  v_available := v_rec.remaining_amount + case when v_rec.id = v_old.receivable_id then v_old.amount else 0 end;
  if v_amount <= 0 then raise exception 'المبلغ المقبوض يجب أن يكون أكبر من صفر.'; end if;
  if v_amount > v_available then raise exception 'المبلغ المقبوض أكبر من المبلغ المتبقي.'; end if;
  v_pct := coalesce(nullif(p_values->>'commission_percentage','')::numeric,v_rec.commission_percentage);
  if v_pct < 0 or v_pct > 100 then raise exception 'نسبة العمولة يجب أن تكون بين 0 و100.'; end if;
  v_commission := round(v_amount * v_pct / 100, 4);
  update public.collections set
    receipt_number = coalesce(nullif(p_values->>'receipt_number',''),receipt_number),
    customer_id = v_rec.customer_id,
    receivable_id = v_rec.id,
    representative_id = v_rec.representative_id,
    amount = v_amount,
    commission_percentage = v_pct,
    commission_amount = v_commission,
    net_amount = v_amount - v_commission,
    collection_date = coalesce(nullif(p_values->>'collection_date','')::date,collection_date),
    payment_method = coalesce(nullif(p_values->>'payment_method',''),payment_method),
    notes = coalesce(p_values->>'notes',notes),
    updated_at = now()
  where id = p_id returning * into v_row;
  return v_row;
end;
$$;

create or replace function public.cancel_collection(p_id bigint, p_reason text default '')
returns boolean
language plpgsql
security invoker
as $$
begin
  update public.collections
     set status='cancelled', cancelled_at=now(), cancelled_by=public.current_profile_id(),
         notes=concat_ws(E'\n',nullif(notes,''),case when coalesce(p_reason,'')<>'' then 'سبب الإلغاء: '||p_reason end), updated_at=now()
   where id=p_id and status='active';
  if not found then raise exception 'عملية القبض غير موجودة أو ملغاة مسبقاً.'; end if;
  return true;
end;
$$;

create or replace function public.create_settlement(p_values jsonb)
returns public.settlements
language plpgsql
security invoker
as $$
declare
  v_rep bigint;
  v_amount numeric;
  v_due numeric;
  v_delivered numeric;
  v_row public.settlements;
begin
  v_rep := (p_values->>'representative_id')::bigint;
  v_amount := (p_values->>'amount')::numeric;
  if v_amount <= 0 then raise exception 'المبلغ المسلم يجب أن يكون أكبر من صفر.'; end if;
  select coalesce(sum(net_amount),0) into v_due from public.collections where representative_id=v_rep and status='active';
  select coalesce(sum(amount),0) into v_delivered from public.settlements where representative_id=v_rep;
  if v_amount > (v_due-v_delivered) then raise exception 'المبلغ المسلم أكبر من الرصيد المستحق على المندوب.'; end if;
  insert into public.settlements(number,representative_id,amount,settlement_date,payment_method,reference_number,received_by,notes,created_by)
  values(coalesce(p_values->>'number',''),v_rep,v_amount,coalesce(nullif(p_values->>'settlement_date','')::date,current_date),coalesce(nullif(p_values->>'payment_method',''),'cash'),coalesce(p_values->>'reference_number',''),coalesce(nullif(p_values->>'received_by',''),(select full_name from public.profiles where id=public.current_profile_id())),coalesce(p_values->>'notes',''),public.current_profile_id())
  returning * into v_row;
  return v_row;
end;
$$;

create or replace function public.transfer_customer(p_customer_id bigint, p_representative_id bigint, p_notes text default '')
returns public.customers
language plpgsql
security invoker
as $$
declare
  v_row public.customers;
