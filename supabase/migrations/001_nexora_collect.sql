create or replace view public.representative_summaries with (security_invoker=true) as
select r.*,
  (select count(*) from public.customers c where c.representative_id=r.id and c.status='active') customer_count,
  (select coalesce(sum(amount),0) from public.collections c where c.representative_id=r.id and c.status='active') collected,
  (select coalesce(sum(commission_amount),0) from public.collections c where c.representative_id=r.id and c.status='active') commissions,
  (select coalesce(sum(net_amount),0) from public.collections c where c.representative_id=r.id and c.status='active') net,
  (select coalesce(sum(amount),0) from public.settlements s where s.representative_id=r.id) settlements
from public.representatives r;

create or replace view public.customer_summaries with (security_invoker=true) as
select c.*,r.name representative_name,
  (select coalesce(sum(original_amount),0) from public.receivables rv where rv.customer_id=c.id and rv.status<>'cancelled') total_receivable,
  (select coalesce(sum(amount),0) from public.collections cl where cl.customer_id=c.id and cl.status='active') collected,
  (select coalesce(sum(remaining_amount),0) from public.receivables rv where rv.customer_id=c.id and rv.status<>'cancelled') remaining
from public.customers c left join public.representatives r on r.id=c.representative_id;

create or replace view public.receivable_details with (security_invoker=true) as
select rv.*,cu.name customer_name,r.name representative_name
from public.receivables rv join public.customers cu on cu.id=rv.customer_id left join public.representatives r on r.id=rv.representative_id;

create or replace view public.collection_details with (security_invoker=true) as
select cl.*,cu.name customer_name,cu.phone customer_phone,r.name representative_name,rv.number receivable_number,rv.description receivable_description,p.full_name created_by_name
from public.collections cl join public.customers cu on cu.id=cl.customer_id left join public.representatives r on r.id=cl.representative_id join public.receivables rv on rv.id=cl.receivable_id left join public.profiles p on p.id=cl.created_by;

create or replace view public.settlement_details with (security_invoker=true) as
select s.*,r.name representative_name,p.full_name created_by_name
from public.settlements s join public.representatives r on r.id=s.representative_id left join public.profiles p on p.id=s.created_by;

create or replace view public.customer_assignment_details with (security_invoker=true) as
select a.*,r.name representative_name,p.full_name changed_by_name
from public.customer_assignments a left join public.representatives r on r.id=a.representative_id left join public.profiles p on p.id=a.changed_by;

