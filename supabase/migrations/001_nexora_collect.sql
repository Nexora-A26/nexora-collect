  paid_amount numeric(18,4) not null default 0,
  remaining_amount numeric(18,4) not null default 0,
  commission_percentage numeric(7,4) not null default 0 check (commission_percentage between 0 and 100),
  issue_date date not null default current_date,
  due_date date,
  status text not null default 'unpaid' check (status in ('unpaid','partial','paid','overdue','cancelled')),
