create table if not exists public.collections (
  id bigint generated by default as identity primary key,
  operation_token uuid unique,
  receipt_number text not null unique,
  customer_id bigint not null references public.customers(id) on delete restrict,
  receivable_id bigint not null references public.receivables(id) on delete restrict,
  representative_id bigint references public.representatives(id) on delete set null,
  amount numeric(18,4) not null check (amount > 0),
  commission_percentage numeric(7,4) not null check (commission_percentage between 0 and 100),
  commission_amount numeric(18,4) not null,
  net_amount numeric(18,4) not null,
  collection_date date not null default current_date,
  payment_method text not null default 'cash',
  notes text default '',
  status text not null default 'active' check (status in ('active','cancelled')),
  cancelled_at timestamptz,
  cancelled_by bigint references public.profiles(id) on delete set null,
